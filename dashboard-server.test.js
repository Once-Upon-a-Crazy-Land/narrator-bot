import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { once } from 'node:events';
import { createDashboardHandler } from './dashboard-server.js';

test('dashboard login, permission checks, CSRF protection and settings validation', async t => {
  const guildId = '123456789012345678';
  let allow = true, writes = 0;
  const guild = { id: guildId, members: { fetch: async () => ({ permissions: { has: () => allow } }) }, channels: { fetch: async () => new Map([['channel', { type: 0 }]]) }, roles: { fetch: async () => new Map() } };
  const client = { isReady: () => true, guilds: { cache: new Map([[guildId, guild]]) } };
  const server = http.createServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => { server.closeAllConnections(); server.close(); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  server.on('request', createDashboardHandler({ client, env: { CLIENT_ID: 'app', DISCORD_CLIENT_SECRET: 'secret', DASHBOARD_URL: origin }, getGuildData: async () => ({ name: 'Test' }), updateGuildSettings: () => { writes++; }, fetcher: async url => ({ ok: true, json: async () => url.endsWith('/oauth2/token') ? { access_token: 'token', expires_in: 3600 } : url.endsWith('/guilds') ? [{ id: guildId, permissions: '32' }] : { id: 'user', username: 'Tester' } }) }));
  const request = (path, options = {}) => fetch(origin + path, { redirect: 'manual', ...options });
  assert.equal((await request('/')).status, 200);
  assert.equal((await request('/health')).status, 200);
  assert.equal((await request('/.env')).status, 401);
  assert.equal((await request('/api/guilds')).status, 401);
  const login = await request('/auth/login');
  let cookie = login.headers.get('set-cookie').split(';')[0];
  const state = new URL(login.headers.get('location')).searchParams.get('state');
  assert.equal((await request('/auth/callback?state=bad&code=x', { headers: { cookie } })).status, 400);
  const callback = await request(`/auth/callback?state=${state}&code=x`, { headers: { cookie } });
  assert.equal(callback.status, 302); cookie = callback.headers.get('set-cookie').split(';')[0];
  const session = await (await request('/api/session', { headers: { cookie } })).json();
  assert.equal(session.user.name, 'Tester');
  assert.equal((await request(`/api/guilds/${guildId}`, { headers: { cookie } })).status, 200);
  const body = JSON.stringify({ roleplayEnabled: true, sayChannels: ['channel'], adminRoles: [], dungeonMasterRoles: [] });
  assert.equal((await request(`/api/guilds/${guildId}`, { method: 'PUT', headers: { cookie }, body })).status, 403);
  const headers = { cookie, origin, 'x-csrf-token': session.csrf };
  assert.equal((await request(`/api/guilds/${guildId}`, { method: 'PUT', headers, body })).status, 200); assert.equal(writes, 1);
  assert.equal((await request(`/api/guilds/${guildId}`, { method: 'PUT', headers, body: body.replace('channel', 'foreign') })).status, 400);
  allow = false;
  assert.equal((await request(`/api/guilds/${guildId}`, { headers })).status, 403);
  assert.equal((await request(`/api/guilds/${guildId}`, { method: 'PUT', headers, body })).status, 403); assert.equal(writes, 1);
  assert.equal((await request('/auth/logout', { method: 'POST', headers })).status, 200);
  assert.equal((await request('/api/guilds', { headers })).status, 401);
});
